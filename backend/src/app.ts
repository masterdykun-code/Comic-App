import express from 'express';
import epubImportRouter from './routes/epub-import.routes';
import bookmarkRouter from './routes/bookmark.routes';
import coinRouter from './routes/coin.routes';
import cors from 'cors';
import healthRouter from './routes/health.routes';
import genreRouter from './routes/genre.routes';
import adminGenreRouter from './routes/admin-genre.routes';
import authRouter from './routes/auth.routes';
import adminUsersRouter from './routes/admin-users.routes';
import passwordResetRouter from './routes/password-reset.routes';
import { storyRouter, adminStoryRouter } from './routes/story.routes';
import chapterRouter from './routes/chapter.routes';
import uploadRouter from './routes/upload.routes';
import favoriteRouter from './routes/favorite.routes';
import readingProgressRouter from './routes/reading-progress.routes';
import readingHistoryRouter from './routes/reading-history.routes';
import ratingRouter from './routes/rating.routes';
import commentRouter from './routes/comment.routes';
import rankingRouter from './routes/ranking.routes';
import { errorHandler, notFoundHandler } from './middlewares/error-handler';

const app = express();

app.use(cors());
app.use(epubImportRouter);
app.use('/api/admin/uploads', uploadRouter);
app.use(chapterRouter);
app.use(express.json({ limit: '16kb' }));
app.use(coinRouter);
app.use('/api/health', healthRouter);
app.use('/api/genres', genreRouter);
app.use('/api/admin/genres', adminGenreRouter);
app.use('/api/auth', authRouter);
app.use('/api/admin', adminUsersRouter);
app.use('/api/auth', passwordResetRouter);
app.use('/api/me/favorites', favoriteRouter);
app.use('/api/me/reading-progress', readingProgressRouter);
app.use('/api/me/reading-history', readingHistoryRouter);
app.use('/api/me/bookmarks', bookmarkRouter);
app.use(ratingRouter);
app.use(commentRouter);
app.use('/api/stories/rankings', rankingRouter);
app.use('/api/stories', storyRouter);
app.use('/api/admin/stories', adminStoryRouter);
app.use(notFoundHandler);
app.use(errorHandler);

export default app;
